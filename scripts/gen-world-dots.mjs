// Generates data/world-dots.ts — a dot-matrix world map (equirectangular, 1000x500).
// Run: node scripts/gen-world-dots.mjs   (needs devDependencies: world-atlas, topojson-client, d3-geo)
import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const topo = JSON.parse(readFileSync("node_modules/world-atlas/land-110m.json", "utf8"));
const land = feature(topo, topo.objects.land);
const STEP = 2.8;
const dots = [];
for (let lat = 82; lat >= -56; lat -= STEP) {
  for (let lon = -180; lon <= 180; lon += STEP) {
    if (geoContains(land, [lon, lat])) {
      dots.push([Math.round(((lon + 180) / 360) * 1000), Math.round(((90 - lat) / 180) * 500)]);
    }
  }
}
writeFileSync(
  "data/world-dots.ts",
  `// AUTO-GENERATED by scripts/gen-world-dots.mjs — do not edit.\nexport const worldDots: [number, number][] = ${JSON.stringify(dots)};\n`,
);
console.log("dots:", dots.length);
